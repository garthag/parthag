// Builds dist/Code.gs (one file to paste into Apps Script) and the AppSheet
// column guide from the schema. Usage: node build.mjs
import { build } from 'esbuild'
import { readdirSync, readFileSync, writeFileSync, copyFileSync, mkdirSync } from 'node:fs'
import vm from 'node:vm'

mkdirSync('dist', { recursive: true })
const engine = await build({ entryPoints: ['src/engine.ts'], bundle: true, format: 'iife', globalName: 'CDPR_ENGINE', target: 'es2019', write: false })
const gas = readdirSync('src/gas').filter((f) => f.endsWith('.js')).sort()
  .map((f) => `// ===== ${f} =====\n` + readFileSync(`src/gas/${f}`, 'utf8')).join('\n')
const banner = `/**
 * CONSTRUCT DPR — Google Workspace edition (Apps Script).
 * GENERATED by google-workspace/build.mjs — edit src/ and rebuild, do not edit here.
 * Paste this whole file into Extensions → Apps Script (Code.gs) of your spreadsheet.
 * Licence: Apache-2.0.
 */\n`
const code = banner + '// ===== engine (shared with the web edition) =====\n' + engine.outputFiles[0].text + '\n' + gas
writeFileSync('dist/Code.gs', code)
copyFileSync('appsscript.json', 'dist/appsscript.json')

// AppSheet guide generated from the schema
const ctx = {}
vm.createContext(ctx)
vm.runInContext(readFileSync('src/gas/00_schema.js', 'utf8'), ctx)
const S = vm.runInContext('SCHEMA', ctx)
let md = `# AppSheet column settings (generated from the schema — do not edit)\n\nFor each table: in AppSheet open **Data → Tables → <table> → View columns** and set the columns as below.\n**script** columns are calculated by Apps Script: untick *Editable* (or set *Editable_If* = FALSE) and *Show* where noted.\n\n`
for (const [name, t] of Object.entries(S)) {
  if (t.appsheet === false) continue
  md += `## ${name}\n\n${t.purpose}${t.appsheetReadOnly ? ' **Add as read-only** (Are updates allowed? → Read-only).' : ''}\n\n| Column | Type | Filled by | Settings |\n|---|---|---|---|\n`
  for (const c of t.cols) {
    const s = []
    if (c.key) s.push('**Key**')
    if (c.ref) s.push(`Source table: ${c.ref}${c.isPartOf ? ' · **Is a part of** ✓' : ''}`)
    if (c.enum) s.push(`Values: ${c.enum.join(', ')}`)
    if (c.by === 'script') s.push('Editable: off')
    if (c.note) s.push(c.note)
    md += `| ${c.n} | ${c.t} | ${c.by} | ${s.join(' · ')} |\n`
  }
  md += '\n'
}
writeFileSync('../docs/APPSHEET_COLUMNS.md', md)
console.log(`dist/Code.gs ${(code.length / 1024).toFixed(1)} KB · ${gas.split('\n').length} lines of workflow code · docs/APPSHEET_COLUMNS.md`)

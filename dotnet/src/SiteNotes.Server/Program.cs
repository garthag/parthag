using System.Text.RegularExpressions;
using Microsoft.AspNetCore.Http.Features;
using Microsoft.AspNetCore.SignalR;
using SiteNotes.Core.Sync;
using SiteNotes.Server;

// SiteNotes sync server: run it on an office PC, a site server or any cloud VM.
// Devices push/pull over HTTP and get real-time "something changed" pings over SignalR.

var builder = WebApplication.CreateBuilder(args);
var maxUpload = builder.Configuration.GetValue("SiteNotes:MaxUploadMb", 500) * 1024L * 1024L;
builder.WebHost.ConfigureKestrel(k => k.Limits.MaxRequestBodySize = maxUpload);
builder.Services.Configure<FormOptions>(o => o.MultipartBodyLengthLimit = maxUpload);
builder.Services.ConfigureHttpJsonOptions(o =>
{
    o.SerializerOptions.PropertyNamingPolicy = SyncJson.Options.PropertyNamingPolicy;
    foreach (var conv in SyncJson.Options.Converters) o.SerializerOptions.Converters.Add(conv);
});
builder.Services.AddSingleton<SyncStore>();
builder.Services.AddSignalR(o => o.MaximumReceiveMessageSize = 64 * 1024);

var app = builder.Build();
var apiKey = app.Configuration["SiteNotes:ApiKey"] ?? "";
var mediaFolder = Path.GetFullPath(app.Configuration["SiteNotes:MediaFolder"] ?? "media");
Directory.CreateDirectory(mediaFolder);

var store = app.Services.GetRequiredService<SyncStore>();
await store.InitializeAsync();

// Shared site key: every request must send X-Api-Key (or ?key= for browsers).
app.Use(async (ctx, next) =>
{
    if (ctx.Request.Path.StartsWithSegments("/api/health") || string.IsNullOrEmpty(apiKey))
    {
        await next();
        return;
    }
    var key = ctx.Request.Headers[SyncJson.ApiKeyHeader].FirstOrDefault() ?? ctx.Request.Query["key"].FirstOrDefault();
    if (key != apiKey)
    {
        ctx.Response.StatusCode = StatusCodes.Status401Unauthorized;
        await ctx.Response.WriteAsync("Missing or wrong site key");
        return;
    }
    await next();
});

app.MapGet("/api/health", () => Results.Ok(new { status = "ok", time = DateTime.UtcNow }));
app.MapGet("/api/stats", async () => Results.Ok(await store.StatsAsync()));

app.MapPost("/api/sync/push", async (PushRequest req, IHubContext<SyncHub> hub) =>
{
    var res = await store.PushAsync(req);
    if (res.Accepted > 0)
        await hub.Clients.All.SendAsync(SyncJson.ChangedMethod, res.ServerVersion, req.DeviceId);
    return Results.Ok(res);
});

app.MapGet("/api/sync/pull", async (long since, int? take) => Results.Ok(await store.PullAsync(since, take ?? 500)));

// Media files (photos, videos, scanned pages, scan PDFs). Names are generated by the app: GUID + extension.
var safeName = new Regex(@"^[A-Za-z0-9_\-]{1,80}\.[A-Za-z0-9]{1,6}$", RegexOptions.Compiled);

app.MapPut("/api/media/{name}", async (string name, HttpRequest req, IHubContext<SyncHub> hub) =>
{
    if (!safeName.IsMatch(name)) return Results.BadRequest("Bad file name");
    var path = Path.Combine(mediaFolder, name);
    var tmp = path + ".part";
    await using (var fs = File.Create(tmp)) await req.Body.CopyToAsync(fs);
    File.Move(tmp, path, true);
    await hub.Clients.All.SendAsync(SyncJson.ChangedMethod, await store.CurrentVersionAsync(), "media");
    return Results.Ok();
});

app.MapGet("/api/media/{name}", (string name) =>
{
    if (!safeName.IsMatch(name)) return Results.BadRequest("Bad file name");
    var path = Path.Combine(mediaFolder, name);
    return File.Exists(path) ? Results.File(path, "application/octet-stream", enableRangeProcessing: true) : Results.NotFound();
});

app.MapHub<SyncHub>(SyncJson.HubPath);

app.Logger.LogInformation("SiteNotes server using {Provider}, media in {Media}", store.IsSqlServer ? "SQL Server" : "SQLite", mediaFolder);
app.Run();

/// <summary>Clients only listen; the server sends "Changed(version, deviceId)" after each accepted push.</summary>
public class SyncHub : Hub;

public partial class Program;

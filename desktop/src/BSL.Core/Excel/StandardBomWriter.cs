using ClosedXML.Excel;

namespace BSL.Core.Excel;

/// <summary>Writes the BOM workbook back to Excel with every sheet in the SAME standard layout.</summary>
public static class StandardBomWriter
{
    public sealed record Col(string Header, Func<StdBomRow, object?> Get, double Width, string? Format = null, bool Sum = false);

    public static readonly Col[] Columns =
    [
        new("S.No", r => r.SNo, 6),
        new("Package", r => r.Package, 16),
        new("Drawing No (base)", r => r.DrawingNo, 30),
        new("Sheet", r => r.SheetNo, 7),
        new("Rev", r => r.Revision, 6),
        new("Drawing Description", r => r.DrawingDescription, 34),
        new("Item Description", r => r.ItemDescription, 22),
        new("Assembly Mark", r => r.AssemblyMark, 12),
        new("Part Mark", r => r.PartMark, 10),
        new("Item No", r => r.ItemNo, 8),
        new("Part Qty", r => r.PartQty, 8, "0.##"),
        new("Section (as per Drg)", r => r.SectionDrg, 28),
        new("Section (Std)", r => r.SectionStd, 18),
        new("Length (mm)", r => r.LengthMm, 10, "0.##"),
        new("Width (mm)", r => r.WidthMm, 10, "0.##"),
        new("Thk (mm)", r => r.ThicknessMm, 8, "0.##"),
        new("No. of Pcs", r => r.Qty, 8, "0.##"),
        new("Qty (text)", r => r.QtyText, 8),
        new("Unit (as in sheet)", r => r.SourceUnitWt, 10, "0.####"),
        new("Unit Wt (kg/pc)", r => r.UnitWeightKg, 11, "#,##0.00"),
        new("Total Wt (kg)", r => r.TotalWeightKg, 12, "#,##0.00", true),
        new("Material Grade", r => r.MaterialGrade, 22),
        new("Material Grade (as in sheet)", r => r.MaterialGradeRaw, 22),
        new("Remarks", r => r.Remarks, 22),
        new("Section Change", r => r.SectionChange, 12),
        new("Dimension Std", r => r.DimensionStd, 12),
        new("Row Type", r => r.RowType, 10),
        new("Excluded", r => r.IsExcluded ? "Yes" : null, 8),
        new("Counted Wt (kg)", r => r.IsExcluded ? 0d : r.TotalWeightKg, 12, "#,##0.00", true),
        new("Quality Flags", r => r.FlagText, 40),
        new("Drawing (as in sheet)", r => r.DrawingRaw, 34),
        new("Source Sheet", r => r.SourceSheet, 16),
        new("Source Row", r => r.SourceRow, 8)
    ];

    static readonly XLColor HeaderFill = XLColor.FromHtml("#1F4E78");
    static readonly XLColor TotalFill = XLColor.FromHtml("#DDEBF7");
    static readonly XLColor ExcludedFont = XLColor.FromHtml("#808080");
    static readonly XLColor FlagFill = XLColor.FromHtml("#FFF2CC");

    public static void Write(BomWorkbook src, string path)
    {
        using var wb = new XLWorkbook();
        var used = new HashSet<string>();
        WriteReadme(wb, src, used);
        WriteSummary(wb, src, used);
        foreach (var p in src.Packages) WriteRows(wb.AddWorksheet(ExcelUtil.SafeSheetName(p.SheetName, used)), p.Rows, p.Title, p.NoOfSets);
        WriteRows(wb.AddWorksheet(ExcelUtil.SafeSheetName("ALL_BOM", used)), src.AllRows.ToList(), "All packages – combined", 1);
        WriteDrawings(wb.AddWorksheet(ExcelUtil.SafeSheetName("DRAWING_REGISTER", used)), src);
        WriteIssues(wb.AddWorksheet(ExcelUtil.SafeSheetName("DATA_ISSUES", used)), src.Issues);
        WriteMapping(wb.AddWorksheet(ExcelUtil.SafeSheetName("COLUMN_MAPPING", used)), src);
        wb.SaveAs(path);
    }

    static void WriteReadme(XLWorkbook wb, BomWorkbook src, ISet<string> used)
    {
        var ws = wb.AddWorksheet(ExcelUtil.SafeSheetName("README", used));
        string[] lines =
        [
            "STANDARDISED BOM – generated by BSL Project Control",
            $"Source file: {src.FileName}    Generated: {DateTime.Now:dd-MM-yyyy HH:mm}",
            "",
            "Every package sheet now has the same columns in the same order (see COLUMN_MAPPING for how each source column was mapped).",
            "Rules applied:",
            " • Header row detected automatically (row 2 or 3); 'UNIT / TOTAL' sub-headers resolved.",
            " • Drawing number split into base number + sheet + revision (e.g. ERC/MCK/BSL/STH/F-001_R3 (SH. 1OF 1) → F-001, 1/1, R3).",
            " • Revisions written as R0, R1 … ; letter revisions (A, B) kept.",
            " • Sheet numbers that Excel had turned into dates (02-Mar) restored to 2/3.",
            " • Weights stored in MT (STOVE NOZZLES) converted to kg. Unit Wt (kg/pc) = Total Wt / No. of Pcs for every sheet.",
            " • Section (Std): PL-<thk>, ISMC150, ISA75X75X6, PIPE OD168.3X5.56, FLANGE DN600, BOLT M20 …",
            " • Material grade typos corrected (15:2002 → IS 2002, IS2062 → IS 2062, Gr .- 2 → Gr.2); original kept in its own column.",
            " • Assembly header rows (mark without part) are marked ASSEMBLY and excluded from totals – their parts are counted instead.",
            " • Set multipliers found in total formulas (×3 stoves, ×4 sets) moved to the 'Sets' column in SUMMARY.",
            " • Total / sub-total rows removed from the data; totals are recalculated with SUBTOTAL so filters work.",
            " • Anything unusual is listed in 'Quality Flags' and in DATA_ISSUES.",
        ];
        for (int i = 0; i < lines.Length; i++) ws.Cell(i + 1, 1).Value = lines[i];
        ws.Cell(1, 1).Style.Font.SetBold().Font.SetFontSize(14);
        ws.Column(1).Width = 140;
    }

    static void WriteSummary(XLWorkbook wb, BomWorkbook src, ISet<string> used)
    {
        var ws = wb.AddWorksheet(ExcelUtil.SafeSheetName("SUMMARY", used));
        string[] h = ["Package (sheet)", "Title", "Header row", "Lines", "Excluded lines", "Drawings", "Sets", "Wt / set (MT)", "Wt all sets (MT)", "Sheet total / set (MT)", "Difference (MT)", "Lines with flags"];
        for (int c = 0; c < h.Length; c++) ws.Cell(1, c + 1).Value = h[c];
        int r = 2;
        foreach (var p in src.Packages)
        {
            ws.Cell(r, 1).Value = p.SheetName;
            ws.Cell(r, 2).Value = p.Title;
            ws.Cell(r, 3).Value = p.HeaderRow;
            ws.Cell(r, 4).Value = p.Rows.Count;
            ws.Cell(r, 5).Value = p.Rows.Count(x => x.IsExcluded);
            ws.Cell(r, 6).Value = p.Rows.Select(x => x.DrawingNo).Concat(p.DrawingOnlyRows.Select(x => x.DrawingNo)).Where(x => x != null).Distinct().Count();
            ws.Cell(r, 7).Value = p.NoOfSets;
            ws.Cell(r, 8).Value = Math.Round(p.CountedWeightKg / 1000, 3);
            ws.Cell(r, 9).FormulaA1 = $"H{r}*G{r}";
            if (p.SheetTotalMt is { } st) { ws.Cell(r, 10).Value = Math.Round(st, 3); ws.Cell(r, 11).FormulaA1 = $"H{r}-J{r}"; }
            ws.Cell(r, 12).Value = p.Rows.Count(x => x.Flags.Count > 0);
            r++;
        }
        ws.Cell(r, 1).Value = "TOTAL";
        foreach (var c in new[] { 4, 5, 6, 8, 9, 10, 11, 12 })
            ws.Cell(r, c).FormulaA1 = $"SUM({ws.Cell(2, c).Address}:{ws.Cell(r - 1, c).Address})";
        StyleTable(ws, 1, r, h.Length);
        ws.Range(2, 8, r, 11).Style.NumberFormat.Format = "#,##0.000";
        ws.Columns().AdjustToContents(1, r, 8, 50);
    }

    public static void WriteRows(IXLWorksheet ws, IList<StdBomRow> rows, string title, int sets)
    {
        ws.Cell(1, 1).Value = title + (sets > 1 ? $"   (No. of sets: {sets})" : "");
        ws.Cell(1, 1).Style.Font.SetBold().Font.SetFontSize(13);
        const int hr = 2;
        for (int c = 0; c < Columns.Length; c++)
        {
            ws.Cell(hr, c + 1).Value = Columns[c].Header;
            ws.Column(c + 1).Width = Columns[c].Width;
        }
        // bulk write values: much faster than cell-by-cell styling
        var data = rows.Select(r => Columns.Select(c => c.Get(r)).ToArray()).ToList();
        if (data.Count > 0) ws.Cell(hr + 1, 1).InsertData(data.Select(a => a.Select(v => v ?? (object)"").ToArray()));
        // InsertData writes "" for nulls – clear them so cells are truly blank
        int last = hr + rows.Count;
        for (int c = 0; c < Columns.Length; c++)
        {
            if (Columns[c].Format is { } fmt && rows.Count > 0) ws.Range(hr + 1, c + 1, last, c + 1).Style.NumberFormat.Format = fmt;
        }
        foreach (var cell in ws.Range(hr + 1, 1, Math.Max(hr + 1, last), Columns.Length).CellsUsed(c => c.Value.IsText && c.Value.GetText().Length == 0))
            cell.Clear(XLClearOptions.Contents);

        for (int i = 0; i < rows.Count; i++)
        {
            if (rows[i].IsExcluded) ws.Row(hr + 1 + i).Style.Font.FontColor = ExcludedFont;
            else if (rows[i].Flags.Count > 0) ws.Cell(hr + 1 + i, Array.FindIndex(Columns, x => x.Header == "Quality Flags") + 1).Style.Fill.BackgroundColor = FlagFill;
        }

        var tot = last + 1;
        ws.Cell(tot, 2).Value = "TOTAL (per set, filtered rows)";
        for (int c = 0; c < Columns.Length; c++)
            if (Columns[c].Sum && rows.Count > 0)
                ws.Cell(tot, c + 1).FormulaA1 = $"SUBTOTAL(9,{ws.Cell(hr + 1, c + 1).Address}:{ws.Cell(last, c + 1).Address})";
        var countedCol = Array.FindIndex(Columns, x => x.Header == "Counted Wt (kg)") + 1;
        ws.Cell(tot + 1, 2).Value = "TOTAL (MT) – all sets";
        ws.Cell(tot + 1, countedCol).FormulaA1 = $"{ws.Cell(tot, countedCol).Address}/1000*{sets}";
        ws.Range(tot, 1, tot + 1, Columns.Length).Style.Fill.BackgroundColor = TotalFill;
        ws.Range(tot, 1, tot + 1, Columns.Length).Style.Font.SetBold();
        ws.Range(tot, 1, tot + 1, Columns.Length).Style.NumberFormat.Format = "#,##0.00";

        var hdr = ws.Range(hr, 1, hr, Columns.Length);
        hdr.Style.Font.SetBold().Font.SetFontColor(XLColor.White).Fill.SetBackgroundColor(HeaderFill).Alignment.SetWrapText();
        hdr.Style.Alignment.Vertical = XLAlignmentVerticalValues.Center;
        ws.Row(hr).Height = 30;
        if (rows.Count > 0) ws.Range(hr, 1, last, Columns.Length).SetAutoFilter();
        ws.SheetView.FreezeRows(hr);
        ws.SheetView.FreezeColumns(3);
    }

    static void WriteDrawings(IXLWorksheet ws, BomWorkbook src)
    {
        string[] h = ["Drawing No (base)", "Sheet", "Rev", "Drawing Description", "Package", "Originator", "BOM lines", "Counted Wt (kg)", "Drawing (as in sheet)", "Index row only"];
        for (int c = 0; c < h.Length; c++) ws.Cell(1, c + 1).Value = h[c];
        var all = src.Packages.SelectMany(p => p.Rows.Select(r => (r, idx: false)).Concat(p.DrawingOnlyRows.Select(r => (r, idx: true))))
                     .Where(x => x.r.DrawingNo != null)
                     .GroupBy(x => (x.r.DrawingNo, x.r.SheetNo, x.r.Revision, x.r.Package))
                     .OrderBy(g => g.Key.Package).ThenBy(g => g.Key.DrawingNo).ThenBy(g => g.Key.SheetNo);
        int r = 2;
        foreach (var g in all)
        {
            var first = g.First().r;
            ws.Cell(r, 1).Value = g.Key.DrawingNo;
            ws.Cell(r, 2).Value = g.Key.SheetNo;
            ws.Cell(r, 3).Value = g.Key.Revision;
            ws.Cell(r, 4).Value = first.DrawingDescription;
            ws.Cell(r, 5).Value = g.Key.Package;
            ws.Cell(r, 6).Value = Standardizer.Originator(g.Key.DrawingNo!);
            ws.Cell(r, 7).Value = g.Count(x => !x.idx);
            ws.Cell(r, 8).Value = Math.Round(g.Where(x => !x.idx && !x.r.IsExcluded).Sum(x => x.r.TotalWeightKg ?? 0), 2);
            ws.Cell(r, 9).Value = first.DrawingRaw;
            ws.Cell(r, 10).Value = g.All(x => x.idx) ? "Yes" : "";
            r++;
        }
        StyleTable(ws, 1, r - 1, h.Length);
        ws.Range(2, 8, r, 8).Style.NumberFormat.Format = "#,##0.00";
        ws.Columns().AdjustToContents(1, Math.Min(r, 300), 8, 60);
    }

    static void WriteIssues(IXLWorksheet ws, List<DataIssue> issues)
    {
        string[] h = ["Sheet", "Row", "Severity", "Code", "Message"];
        for (int c = 0; c < h.Length; c++) ws.Cell(1, c + 1).Value = h[c];
        if (issues.Count > 0)
            ws.Cell(2, 1).InsertData(issues.OrderBy(i => i.Severity == "Warning" ? 0 : 1).ThenBy(i => i.Sheet).ThenBy(i => i.Row)
                .Select(i => new object[] { i.Sheet, i.Row, i.Severity, i.Code, i.Message }));
        StyleTable(ws, 1, issues.Count + 1, h.Length);
        ws.Column(1).Width = 26; ws.Column(2).Width = 7; ws.Column(3).Width = 10; ws.Column(4).Width = 28; ws.Column(5).Width = 120;
    }

    static void WriteMapping(IXLWorksheet ws, BomWorkbook src)
    {
        string[] h = ["Sheet", "Header row", "Standard field @ source column", "Source header"];
        for (int c = 0; c < h.Length; c++) ws.Cell(1, c + 1).Value = h[c];
        int r = 2;
        foreach (var p in src.Packages)
            foreach (var (k, v) in p.ColumnMap)
            {
                ws.Cell(r, 1).Value = p.SheetName; ws.Cell(r, 2).Value = p.HeaderRow; ws.Cell(r, 3).Value = k; ws.Cell(r, 4).Value = v; r++;
            }
        StyleTable(ws, 1, r - 1, h.Length);
        ws.Columns().AdjustToContents(1, r, 8, 60);
    }

    public static void StyleTable(IXLWorksheet ws, int headerRow, int lastRow, int cols)
    {
        var hdr = ws.Range(headerRow, 1, headerRow, cols);
        hdr.Style.Font.SetBold().Font.SetFontColor(XLColor.White).Fill.SetBackgroundColor(HeaderFill);
        if (lastRow > headerRow) ws.Range(headerRow, 1, lastRow, cols).SetAutoFilter();
        ws.SheetView.FreezeRows(headerRow);
    }
}
